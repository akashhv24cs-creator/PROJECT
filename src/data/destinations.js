/**
 * Helper: Retrieve all unique stops & primary destinations in flat searchable format
 */
export function getAllAvailableStops() {
  const list = [];
  const seenIds = new Set();

  // Add primary destinations as stops
  DESTINATIONS.forEach((d) => {
    if (!seenIds.has(d.id)) {
      seenIds.add(d.id);
      list.push({
        id: d.id,
        name: d.name,
        state: d.state,
        type: "Primary Destination",
        distance: d.distance,
        image: d.image,
        alt: d.alt || `${d.name}, ${d.state}`,
        category: d.categories?.[0] || "city-escapes",
        categoryName: d.tagline,
        description: d.description,
        highlights: d.highlights || [],
      });
    }

    // Add all nearby stops
    if (d.nearbyStops) {
      d.nearbyStops.forEach((stop) => {
        if (!seenIds.has(stop.id)) {
          seenIds.add(stop.id);
          list.push({
            id: stop.id,
            name: stop.name,
            state: d.state,
            type: "Nearby Spot",
            distance: stop.distance,
            parentDestination: d.name,
            parentDestinationId: d.id,
            image: stop.image,
            alt: stop.alt || `${stop.name}, ${d.state}`,
            category: stop.category || "nature-wildlife",
            categoryName: stop.categoryName || "Discovery",
            description: stop.description,
            highlights: stop.highlights || [],
          });
        }
      });
    }
  });

  return list;
}

/**
 * Helper: Search across all destinations and stops
 */
export function searchDestinationsAndStops(query = "") {
  const q = query.trim().toLowerCase();
  const allStops = getAllAvailableStops();
  if (!q) return allStops;

  return allStops.filter((item) => {
    return (
      item.name.toLowerCase().includes(q) ||
      (item.state && item.state.toLowerCase().includes(q)) ||
      (item.categoryName && item.categoryName.toLowerCase().includes(q)) ||
      (item.description && item.description.toLowerCase().includes(q)) ||
      (item.highlights && item.highlights.some((h) => h.toLowerCase().includes(q)))
    );
  });
}

/**
 * Helper: Get smart recommendations for current journey
 */
export function getRecommendationsForJourney(primaryDestId, selectedStops = []) {
  const dest = DESTINATIONS.find(
    (d) => d.id.toLowerCase() === (primaryDestId || "").toLowerCase()
  ) || DESTINATIONS[0];

  const existingStopIds = new Set([dest.id, ...selectedStops.map((s) => s.id)]);
  
  // Return primary destination's nearby stops first
  const primaryNearby = (dest.nearbyStops || []).filter((s) => !existingStopIds.has(s.id));

  // If user selected stops from other destinations, include recommendations from those destinations as well
  const additionalNearby = [];
  selectedStops.forEach((stop) => {
    const parent = DESTINATIONS.find(
      (d) => d.id === stop.id || d.id === stop.parentDestinationId
    );
    if (parent && parent.nearbyStops) {
      parent.nearbyStops.forEach((s) => {
        if (!existingStopIds.has(s.id) && !primaryNearby.some((p) => p.id === s.id)) {
          additionalNearby.push(s);
        }
      });
    }
  });

  return [...primaryNearby, ...additionalNearby];
}

